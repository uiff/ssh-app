// schrift: je Zeichen 7 Zeilen, Bit 4 = linker Punkt.
var schrift = func() map[rune][7]uint8 {
	m := make(map[rune][7]uint8, len(schriftQuelle))
	for r, q := range schriftQuelle {
		var g [7]uint8
		for i, zeile := range strings.Fields(q) {
			for _, c := range zeile {
				g[i] <<= 1
				if c == '1' {
					g[i] |= 1
				}
			}
		}
		m[r] = g
	}
	return m
}()

// anzeigeText bringt einen Text in die Zeichen der Schrift (Grossbuchstaben, Umlaute
// ausgeschrieben, Unbekanntes als «?»).
func anzeigeText(s string) string {
	s = strings.NewReplacer("ä", "ae", "ö", "oe", "ü", "ue", "Ä", "AE", "Ö", "OE", "Ü", "UE", "ß", "ss").Replace(s)
	s = strings.ToUpper(s)
	return strings.Map(func(r rune) rune {
		if _, ok := schrift[r]; ok {
			return r
		}
		return '?'
	}, s)
}
