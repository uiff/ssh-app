// erweitern liefert zu einem normalisierten Suchwort die Alternativen (inkl. sich selbst).
func erweitern(w string) []string {
	alt := []string{w}
	for laenge := len(w); laenge >= 3; laenge-- {
		if s, ok := synonyme[w[:laenge]]; ok {
			return append(alt, s...)
		}
	}
	return alt
}

